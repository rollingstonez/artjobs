import type { Posting } from "@/types/job";

function daysFromNow(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return d.toISOString().slice(0, 10);
}

type Seed = Pick<
  Posting,
  "id" | "title" | "organization" | "board" | "field" | "genre" | "role" | "categoryRaw" | "employmentType" | "employmentRaw" | "region"
> &
  Partial<Posting> & { daysAgo: number; daysLeft: number | null };

function make(s: Seed): Posting {
  const { daysAgo, daysLeft, ...rest } = s;
  return {
    address: null,
    salary: null,
    recruitCount: null,
    applyStart: daysFromNow(-daysAgo),
    applyEnd: daysLeft === null ? null : daysFromNow(daysLeft),
    workStart: null,
    workEnd: null,
    applyMethod: null,
    applyEmail: null,
    applyContact: null,
    requiredDocs: null,
    description: null,
    sourceName: "샘플",
    sourceUrl: `https://example.org/notice/${s.id.replace("sample-", "")}`,
    status: "open",
    createdAt: daysFromNow(-daysAgo),
    ...rest,
  };
}

